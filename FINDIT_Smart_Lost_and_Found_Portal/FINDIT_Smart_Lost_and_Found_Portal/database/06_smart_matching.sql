
-- Rule-based fuzzy matching for FINDIT. Run as FINDIT schema.
CREATE OR REPLACE PROCEDURE FIND_MATCHING_ITEMS(P_LOST_ID IN NUMBER, P_RESULTS OUT SYS_REFCURSOR) AS
BEGIN
  OPEN P_RESULTS FOR
    SELECT L.LOST_ID, L.ITEM_NAME LOST_ITEM, F.FOUND_ID, F.ITEM_NAME FOUND_ITEM,
      (CASE WHEN UPPER(TRIM(L.ITEM_NAME))=UPPER(TRIM(F.ITEM_NAME)) THEN 40
            WHEN UTL_MATCH.EDIT_DISTANCE_SIMILARITY(UPPER(L.ITEM_NAME),UPPER(F.ITEM_NAME))>=90 THEN 30
            ELSE 20 END)
      + CASE WHEN L.CATEGORY_ID=F.CATEGORY_ID THEN 30 ELSE 0 END
      + CASE WHEN UPPER(TRIM(L.LOST_LOCATION))=UPPER(TRIM(F.FOUND_LOCATION)) THEN 30 ELSE 0 END MATCH_SCORE
    FROM LOST_ITEMS L JOIN FOUND_ITEMS F ON L.CATEGORY_ID=F.CATEGORY_ID
    WHERE L.LOST_ID=P_LOST_ID AND L.ITEM_STATUS='OPEN' AND F.ITEM_STATUS='OPEN'
      AND UTL_MATCH.EDIT_DISTANCE_SIMILARITY(UPPER(L.ITEM_NAME),UPPER(F.ITEM_NAME))>=60
    ORDER BY MATCH_SCORE DESC;
END;
/
