CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(80) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(256) NOT NULL,
    ROLE VARCHAR2(10) DEFAULT 'USER' NOT NULL
        CHECK (ROLE IN ('USER', 'ADMIN')),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE LOST_ITEMS (
    LOST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    ITEM_NAME VARCHAR2(100) NOT NULL,
    ITEM_DESCRIPTION VARCHAR2(1000),
    LOST_LOCATION VARCHAR2(150) NOT NULL,
    LOST_DATE DATE NOT NULL,
    CONTACT_DETAILS VARCHAR2(120) NOT NULL,
    ITEM_STATUS VARCHAR2(15) DEFAULT 'OPEN' NOT NULL
        CHECK (ITEM_STATUS IN ('OPEN', 'MATCHED', 'CLOSED')),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_LOST_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_LOST_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID)
);

CREATE TABLE FOUND_ITEMS (
    FOUND_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    ITEM_NAME VARCHAR2(100) NOT NULL,
    ITEM_DESCRIPTION VARCHAR2(1000),
    FOUND_LOCATION VARCHAR2(150) NOT NULL,
    FOUND_DATE DATE NOT NULL,
    CONTACT_DETAILS VARCHAR2(120) NOT NULL,
    ITEM_STATUS VARCHAR2(15) DEFAULT 'OPEN' NOT NULL
        CHECK (ITEM_STATUS IN ('OPEN', 'CLAIMED', 'RETURNED', 'CLOSED')),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_FOUND_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_FOUND_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID)
);

CREATE TABLE CLAIMS (
    CLAIM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FOUND_ID NUMBER NOT NULL,
    CLAIMANT_USER_ID NUMBER NOT NULL,
    CLAIM_MESSAGE VARCHAR2(1000),
    CLAIM_STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL
        CHECK (CLAIM_STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CLAIMED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    CONSTRAINT FK_CLAIM_FOUND FOREIGN KEY (FOUND_ID) REFERENCES FOUND_ITEMS(FOUND_ID),
    CONSTRAINT FK_CLAIM_USER FOREIGN KEY (CLAIMANT_USER_ID) REFERENCES USERS(USER_ID)
);

CREATE INDEX IDX_LOST_NAME ON LOST_ITEMS(ITEM_NAME);
CREATE INDEX IDX_FOUND_NAME ON FOUND_ITEMS(ITEM_NAME);
CREATE INDEX IDX_LOST_CATEGORY ON LOST_ITEMS(CATEGORY_ID);
CREATE INDEX IDX_FOUND_CATEGORY ON FOUND_ITEMS(CATEGORY_ID);

COMMIT;
