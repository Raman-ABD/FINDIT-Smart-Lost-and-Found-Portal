-- Keep a claim's review timestamp updated when its status changes.
CREATE OR REPLACE TRIGGER TRG_CLAIM_REVIEW_DATE
BEFORE UPDATE OF CLAIM_STATUS ON CLAIMS
FOR EACH ROW
BEGIN
    IF :NEW.CLAIM_STATUS <> :OLD.CLAIM_STATUS THEN
        :NEW.REVIEWED_AT := SYSTIMESTAMP;
    END IF;
END;
/

-- Basic validation: item dates cannot be in the future.
CREATE OR REPLACE TRIGGER TRG_LOST_DATE_CHECK
BEFORE INSERT OR UPDATE OF LOST_DATE ON LOST_ITEMS
FOR EACH ROW
BEGIN
    IF :NEW.LOST_DATE > TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20021, 'Lost date cannot be in the future.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_FOUND_DATE_CHECK
BEFORE INSERT OR UPDATE OF FOUND_DATE ON FOUND_ITEMS
FOR EACH ROW
BEGIN
    IF :NEW.FOUND_DATE > TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20022, 'Found date cannot be in the future.');
    END IF;
END;
/
