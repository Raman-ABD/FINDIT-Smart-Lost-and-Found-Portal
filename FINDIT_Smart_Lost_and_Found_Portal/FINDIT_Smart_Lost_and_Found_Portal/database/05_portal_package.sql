
-- FINDIT PORTAL EXTENSION
-- Run as FINDIT schema after 01_create_tables.sql and 03_package.sql.
-- Demo password hashing uses SHA-256 via STANDARD_HASH. For production, use a
-- dedicated password hashing/KDF solution and real server-side sessions.

CREATE OR REPLACE PACKAGE FINDIT_PORTAL_PKG AS
  PROCEDURE REGISTER_USER(P_FULL_NAME VARCHAR2, P_EMAIL VARCHAR2, P_PASSWORD VARCHAR2, P_NEW_USER_ID OUT NUMBER);
  PROCEDURE LOGIN_USER(P_EMAIL VARCHAR2, P_PASSWORD VARCHAR2, P_USER_ID OUT NUMBER, P_FULL_NAME OUT VARCHAR2, P_ROLE OUT VARCHAR2);
  PROCEDURE SUBMIT_CLAIM(P_FOUND_ID NUMBER, P_USER_ID NUMBER, P_MESSAGE VARCHAR2, P_NEW_CLAIM_ID OUT NUMBER);
  PROCEDURE REVIEW_CLAIM(P_CLAIM_ID NUMBER, P_STATUS VARCHAR2);
END FINDIT_PORTAL_PKG;
/
CREATE OR REPLACE PACKAGE BODY FINDIT_PORTAL_PKG AS
  PROCEDURE REGISTER_USER(P_FULL_NAME VARCHAR2, P_EMAIL VARCHAR2, P_PASSWORD VARCHAR2, P_NEW_USER_ID OUT NUMBER) IS
  BEGIN
    IF TRIM(P_FULL_NAME) IS NULL OR TRIM(P_EMAIL) IS NULL OR LENGTH(P_PASSWORD) < 8 THEN
      RAISE_APPLICATION_ERROR(-20021,'Enter name, email and a password of at least 8 characters.');
    END IF;
    INSERT INTO USERS(FULL_NAME,EMAIL,PASSWORD_HASH,ROLE)
    VALUES(TRIM(P_FULL_NAME),LOWER(TRIM(P_EMAIL)),STANDARD_HASH(P_PASSWORD,'SHA256'),'USER')
    RETURNING USER_ID INTO P_NEW_USER_ID;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
    RAISE_APPLICATION_ERROR(-20022,'This email is already registered.');
  END;

  PROCEDURE LOGIN_USER(P_EMAIL VARCHAR2, P_PASSWORD VARCHAR2, P_USER_ID OUT NUMBER, P_FULL_NAME OUT VARCHAR2, P_ROLE OUT VARCHAR2) IS
  BEGIN
    SELECT USER_ID,FULL_NAME,ROLE INTO P_USER_ID,P_FULL_NAME,P_ROLE
    FROM USERS
    WHERE EMAIL=LOWER(TRIM(P_EMAIL))
      AND PASSWORD_HASH=STANDARD_HASH(P_PASSWORD,'SHA256');
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20023,'Incorrect email or password.');
  END;

  PROCEDURE SUBMIT_CLAIM(P_FOUND_ID NUMBER, P_USER_ID NUMBER, P_MESSAGE VARCHAR2, P_NEW_CLAIM_ID OUT NUMBER) IS
    V_OWNER NUMBER; V_STATUS VARCHAR2(15);
  BEGIN
    SELECT USER_ID,ITEM_STATUS INTO V_OWNER,V_STATUS FROM FOUND_ITEMS WHERE FOUND_ID=P_FOUND_ID;
    IF V_OWNER=P_USER_ID THEN RAISE_APPLICATION_ERROR(-20024,'You cannot claim your own found item.'); END IF;
    IF V_STATUS <> 'OPEN' THEN RAISE_APPLICATION_ERROR(-20025,'This item is not available for claims.'); END IF;
    INSERT INTO CLAIMS(FOUND_ID,CLAIMANT_USER_ID,CLAIM_MESSAGE)
    VALUES(P_FOUND_ID,P_USER_ID,TRIM(P_MESSAGE))
    RETURNING CLAIM_ID INTO P_NEW_CLAIM_ID;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20026,'Found item not found.');
  END;

  PROCEDURE REVIEW_CLAIM(P_CLAIM_ID NUMBER,P_STATUS VARCHAR2) IS
  BEGIN
    IF UPPER(P_STATUS) NOT IN ('APPROVED','REJECTED') THEN
      RAISE_APPLICATION_ERROR(-20027,'Status must be APPROVED or REJECTED.');
    END IF;
    UPDATE CLAIMS SET CLAIM_STATUS=UPPER(P_STATUS), REVIEWED_AT=SYSTIMESTAMP
    WHERE CLAIM_ID=P_CLAIM_ID AND CLAIM_STATUS='PENDING';
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20028,'Pending claim not found.'); END IF;
    IF UPPER(P_STATUS)='APPROVED' THEN
      UPDATE FOUND_ITEMS SET ITEM_STATUS='CLAIMED'
      WHERE FOUND_ID=(SELECT FOUND_ID FROM CLAIMS WHERE CLAIM_ID=P_CLAIM_ID);
    END IF;
  END;
END FINDIT_PORTAL_PKG;
