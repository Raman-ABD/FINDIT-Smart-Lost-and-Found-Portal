-- FINDIT business logic package.
CREATE OR REPLACE PACKAGE FINDIT_PKG AS
    PROCEDURE ADD_LOST_ITEM (
        P_USER_ID IN NUMBER,
        P_CATEGORY_ID IN NUMBER,
        P_ITEM_NAME IN VARCHAR2,
        P_DESCRIPTION IN VARCHAR2,
        P_LOCATION IN VARCHAR2,
        P_LOST_DATE IN DATE,
        P_CONTACT IN VARCHAR2,
        P_NEW_ID OUT NUMBER
    );

    PROCEDURE ADD_FOUND_ITEM (
        P_USER_ID IN NUMBER,
        P_CATEGORY_ID IN NUMBER,
        P_ITEM_NAME IN VARCHAR2,
        P_DESCRIPTION IN VARCHAR2,
        P_LOCATION IN VARCHAR2,
        P_FOUND_DATE IN DATE,
        P_CONTACT IN VARCHAR2,
        P_NEW_ID OUT NUMBER
    );

    FUNCTION COUNT_OPEN_LOST_ITEMS RETURN NUMBER;
    FUNCTION COUNT_OPEN_FOUND_ITEMS RETURN NUMBER;
END FINDIT_PKG;
/

CREATE OR REPLACE PACKAGE BODY FINDIT_PKG AS
    PROCEDURE ADD_LOST_ITEM (
        P_USER_ID IN NUMBER,
        P_CATEGORY_ID IN NUMBER,
        P_ITEM_NAME IN VARCHAR2,
        P_DESCRIPTION IN VARCHAR2,
        P_LOCATION IN VARCHAR2,
        P_LOST_DATE IN DATE,
        P_CONTACT IN VARCHAR2,
        P_NEW_ID OUT NUMBER
    ) AS
    BEGIN
        INSERT INTO LOST_ITEMS
        (USER_ID, CATEGORY_ID, ITEM_NAME, ITEM_DESCRIPTION,
         LOST_LOCATION, LOST_DATE, CONTACT_DETAILS)
        VALUES
        (P_USER_ID, P_CATEGORY_ID, TRIM(P_ITEM_NAME), P_DESCRIPTION,
         TRIM(P_LOCATION), P_LOST_DATE, TRIM(P_CONTACT))
        RETURNING LOST_ID INTO P_NEW_ID;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20011, 'Duplicate value detected.');
        WHEN VALUE_ERROR THEN
            RAISE_APPLICATION_ERROR(-20012, 'One of the entered values is too long or invalid.');
    END ADD_LOST_ITEM;

    PROCEDURE ADD_FOUND_ITEM (
        P_USER_ID IN NUMBER,
        P_CATEGORY_ID IN NUMBER,
        P_ITEM_NAME IN VARCHAR2,
        P_DESCRIPTION IN VARCHAR2,
        P_LOCATION IN VARCHAR2,
        P_FOUND_DATE IN DATE,
        P_CONTACT IN VARCHAR2,
        P_NEW_ID OUT NUMBER
    ) AS
    BEGIN
        INSERT INTO FOUND_ITEMS
        (USER_ID, CATEGORY_ID, ITEM_NAME, ITEM_DESCRIPTION,
         FOUND_LOCATION, FOUND_DATE, CONTACT_DETAILS)
        VALUES
        (P_USER_ID, P_CATEGORY_ID, TRIM(P_ITEM_NAME), P_DESCRIPTION,
         TRIM(P_LOCATION), P_FOUND_DATE, TRIM(P_CONTACT))
        RETURNING FOUND_ID INTO P_NEW_ID;
    EXCEPTION
        WHEN VALUE_ERROR THEN
            RAISE_APPLICATION_ERROR(-20013, 'One of the entered values is too long or invalid.');
    END ADD_FOUND_ITEM;

    FUNCTION COUNT_OPEN_LOST_ITEMS RETURN NUMBER AS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_TOTAL
        FROM LOST_ITEMS
        WHERE ITEM_STATUS = 'OPEN';
        RETURN V_TOTAL;
    END COUNT_OPEN_LOST_ITEMS;

    FUNCTION COUNT_OPEN_FOUND_ITEMS RETURN NUMBER AS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_TOTAL
        FROM FOUND_ITEMS
        WHERE ITEM_STATUS = 'OPEN';
        RETURN V_TOTAL;
    END COUNT_OPEN_FOUND_ITEMS;
END FINDIT_PKG;
/
